//Data Structures
//Arrays - can be mixed type array or empty arrays other than storing the same type of data in JS
     //  - arrays are mutable - can be changed after creation
     //  - arrays methods - push , pop , shift unshift
let students = ["suman" , "Sai" , "Suraj" ,"Ravi"] ;
console.log(students) ;

students.push("Shiva") ; //adds to the end 
students.pop() ; //removes from the end
students.shift() ;//removes from the start 
students.unshift("Sandesh") ; //adds to the start 

